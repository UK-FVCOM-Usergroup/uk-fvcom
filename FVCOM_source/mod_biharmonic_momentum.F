! FESOM-C-inspired two-pass nearest-cell momentum filter. Independent implementation.
! See Doc/biharmonic_momentum.md for normalization, boundaries and limitations.
MODULE MOD_BIHARMONIC_GRAPH
  USE MOD_PREC, ONLY: SP,DP
  USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_IS_FINITE
  IMPLICIT NONE
  PRIVATE
  PUBLIC :: GRAPH_FILTER_FIRST, GRAPH_FILTER_SECOND
CONTAINS
  PURE SUBROUTINE GRAPH_FILTER_FIRST(N,NT,NL,NB,ACTIVE,Q,COEF,W,ROW,STATUS)
    INTEGER, INTENT(IN) :: N,NT,NL,NB(0:NT,3)
    LOGICAL, INTENT(IN) :: ACTIVE(0:NT)
    REAL(SP), INTENT(IN) :: Q(0:NT,NL+1),COEF(N,NL)
    REAL(SP), INTENT(OUT) :: W(0:NT,NL+1),ROW(0:NT,NL+1)
    INTEGER, INTENT(OUT) :: STATUS
    INTEGER :: I,J,K,L,DEG
    REAL(SP) :: VALUE
    STATUS=0;W=0.0_SP;ROW=0.0_SP
    IF(N<0.OR.NT<N.OR.NL<1) THEN
      STATUS=1;RETURN
    END IF
    DO I=1,N
      IF(.NOT.ACTIVE(I)) CYCLE
      DEG=0
      DO J=1,3
        L=NB(I,J)
        IF(L<0.OR.L>NT.OR.L==I) THEN
          STATUS=2;RETURN
        END IF
        IF(L==0) CYCLE
        IF(.NOT.ANY(NB(L,:)==I)) THEN
          STATUS=2;RETURN
        END IF
        IF(J>1) THEN
          IF(ANY(NB(I,1:J-1)==L)) THEN
            STATUS=2;RETURN
          END IF
        END IF
        IF(ACTIVE(L)) DEG=DEG+1
      END DO
      DO K=1,NL
        IF(.NOT.IEEE_IS_FINITE(Q(I,K)).OR..NOT.IEEE_IS_FINITE(COEF(I,K))) THEN
          STATUS=3;RETURN
        END IF
        IF(COEF(I,K)<0.0_SP) THEN
          STATUS=4;RETURN
        END IF
        VALUE=0.0_SP
        DO J=1,3
          L=NB(I,J)
          IF(L==0) CYCLE
          IF(.NOT.ACTIVE(L)) CYCLE
          IF(.NOT.IEEE_IS_FINITE(Q(L,K))) THEN
            STATUS=3;RETURN
          END IF
          VALUE=VALUE+(Q(I,K)-Q(L,K))
        END DO
        W(I,K)=COEF(I,K)*VALUE
        ROW(I,K)=2.0_SP*REAL(DEG,SP)*COEF(I,K)
      END DO
    END DO
    IF(.NOT.ALL(IEEE_IS_FINITE(W)).OR..NOT.ALL(IEEE_IS_FINITE(ROW))) STATUS=5
  END SUBROUTINE

  PURE SUBROUTINE GRAPH_FILTER_SECOND(N,NT,NL,NB,ACTIVE,W,ROW,MASS,R,RATE,STATUS)
    INTEGER, INTENT(IN) :: N,NT,NL,NB(0:NT,3)
    LOGICAL, INTENT(IN) :: ACTIVE(0:NT)
    REAL(SP), INTENT(IN) :: W(0:NT,NL+1),ROW(0:NT,NL+1),MASS(N,NL)
    REAL(SP), INTENT(OUT) :: R(0:NT,NL+1)
    REAL(DP), INTENT(OUT) :: RATE
    INTEGER, INTENT(OUT) :: STATUS
    INTEGER :: I,J,K,L,DEG
    REAL(DP) :: BOUND
    STATUS=0;R=0.0_SP;RATE=0.0_DP
    DO I=1,N
      IF(.NOT.ACTIVE(I)) CYCLE
      DEG=0
      DO J=1,3
        L=NB(I,J)
        IF(L<0.OR.L>NT.OR.L==I) THEN
          STATUS=2;RETURN
        END IF
        IF(L==0) CYCLE
        IF(ACTIVE(L)) DEG=DEG+1
      END DO
      DO K=1,NL
        IF(.NOT.IEEE_IS_FINITE(MASS(I,K))) THEN
          STATUS=4;RETURN
        END IF
        IF(MASS(I,K)<=0.0_SP) THEN
          STATUS=4;RETURN
        END IF
        BOUND=REAL(DEG,DP)*REAL(ROW(I,K),DP)
        DO J=1,3
          L=NB(I,J)
          IF(L==0) CYCLE
          IF(.NOT.ACTIVE(L)) CYCLE
          R(I,K)=R(I,K)+(W(I,K)-W(L,K))
          BOUND=BOUND+REAL(ROW(L,K),DP)
        END DO
        RATE=MAX(RATE,BOUND/REAL(MASS(I,K),DP))
      END DO
    END DO
    IF(.NOT.ALL(IEEE_IS_FINITE(R)).OR..NOT.IEEE_IS_FINITE(RATE)) STATUS=5
  END SUBROUTINE
END MODULE MOD_BIHARMONIC_GRAPH

MODULE MOD_BIHARMONIC_MOMENTUM
  USE ALL_VARS, ONLY: SP,DP,N,NT,KB,KBM1,NBE,ART,DT1,D1,DZ1,U,V,UA,VA,DTI,DTE, &
       ISBCE,EPOR,NP,IPT,SERIAL,MYID,PAR, &
       MOMENTUM_BIHARMONIC_RATE,MOMENTUM_BIHARMONIC_REFERENCE_AREA
  USE MOD_BIHARMONIC_GRAPH
  USE MOD_UTILS, ONLY: FATAL_ERROR
  USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_IS_FINITE
# if defined (WET_DRY)
  USE ALL_VARS, ONLY: ISWETC,ISWETCT,ISWETCE
# endif
# if defined (MULTIPROCESSOR)
  USE ALL_VARS, ONLY: NPROCS,MPI_FVCOM_GROUP
  USE MOD_PAR, ONLY: AEXCHANGE,EC
  USE MPI, ONLY: MPI_ALLREDUCE,MPI_INTEGER,MPI_MAX,MPI_SUM,MPI_DOUBLE_PRECISION
# endif
  IMPLICIT NONE
  PRIVATE
  PUBLIC :: ADD_BIHARMONIC_3D,ADD_BIHARMONIC_2D,CHECK_BIHARMONIC_CONFIG
  TYPE WORKSPACE
    REAL(SP),ALLOCATABLE :: QX(:,:),QY(:,:),WX(:,:),WY(:,:),ROW(:,:),MASS(:,:),COEF(:,:)
    LOGICAL,ALLOCATABLE :: ACTIVE(:)
  END TYPE
  TYPE(WORKSPACE),SAVE :: WORK3,WORK2
  REAL(DP),SAVE :: REFERENCE_AREA=0.0_DP
CONTAINS
  SUBROUTINE CHECK_STATUS(STATUS,MESSAGE)
    INTEGER,INTENT(IN)::STATUS
    CHARACTER(*),INTENT(IN)::MESSAGE
    INTEGER::GLOBAL_STATUS
# if defined (MULTIPROCESSOR)
    INTEGER::IERR
# endif
    GLOBAL_STATUS=STATUS
# if defined (MULTIPROCESSOR)
    IF(PAR) CALL MPI_ALLREDUCE(STATUS,GLOBAL_STATUS,1,MPI_INTEGER,MPI_MAX,MPI_FVCOM_GROUP,IERR)
# endif
    IF(GLOBAL_STATUS/=0) CALL FATAL_ERROR('BIHARMONIC MOMENTUM: '//MESSAGE)
  END SUBROUTINE

  SUBROUTINE CHECK_BIHARMONIC_CONFIG
    IF(.NOT.IEEE_IS_FINITE(MOMENTUM_BIHARMONIC_RATE)) &
      CALL FATAL_ERROR('MOMENTUM_BIHARMONIC_RATE must be finite and nonnegative (per day)')
    IF(MOMENTUM_BIHARMONIC_RATE<0.0_SP) &
      CALL FATAL_ERROR('MOMENTUM_BIHARMONIC_RATE must be nonnegative (per day)')
    IF(.NOT.IEEE_IS_FINITE(MOMENTUM_BIHARMONIC_REFERENCE_AREA)) &
      CALL FATAL_ERROR('MOMENTUM_BIHARMONIC_REFERENCE_AREA must be finite and nonnegative (m2)')
    IF(MOMENTUM_BIHARMONIC_REFERENCE_AREA<0.0_SP) &
      CALL FATAL_ERROR('MOMENTUM_BIHARMONIC_REFERENCE_AREA must be nonnegative (m2; zero selects mean area)')
    IF(MOMENTUM_BIHARMONIC_RATE==0.0_SP) RETURN
# if defined (SEMI_IMPLICIT) || defined (NH) || defined (ONE_D_MODEL) || defined (PLBC) || defined (THIN_DAM) || defined (ICESHELF)
    CALL FATAL_ERROR('BIHARMONIC MOMENTUM: unsupported time stepping or boundary configuration; see Doc/biharmonic_momentum.md')
# endif
  END SUBROUTINE

  SUBROUTINE PREPARE(W,NL,IS3D)
    TYPE(WORKSPACE),INTENT(INOUT)::W
    INTEGER,INTENT(IN)::NL
    LOGICAL,INTENT(IN)::IS3D
    INTEGER::I,K,STATUS
    REAL(DP)::AREA_SUM(2),TOTAL(2),KAPPA,VOLUME
# if defined (MULTIPROCESSOR)
    INTEGER::IERR
# endif
    STATUS=0
    IF(N<0.OR.NT<N.OR.NL<1.OR.NP>0) STATUS=1
    CALL CHECK_STATUS(STATUS,'invalid dimensions or unsupported north-pole patch')
    IF(.NOT.ALLOCATED(W%QX)) THEN
      ALLOCATE(W%QX(0:NT,NL+1),W%QY(0:NT,NL+1),W%WX(0:NT,NL+1), &
        W%WY(0:NT,NL+1),W%ROW(0:NT,NL+1),W%MASS(N,NL),W%COEF(N,NL),W%ACTIVE(0:NT))
    END IF
    IF(SIZE(W%QX,1)/=NT+1.OR.SIZE(W%QX,2)/=NL+1.OR.SIZE(W%MASS,1)/=N) STATUS=1
    CALL CHECK_STATUS(STATUS,'mesh dimensions changed during execution')
    IF(.NOT.ALL(IEEE_IS_FINITE(ART(1:N)))) STATUS=1
    CALL CHECK_STATUS(STATUS,'nonfinite cell areas')
    IF(.NOT.ALL(ART(1:N)>0.0_SP)) STATUS=1
    CALL CHECK_STATUS(STATUS,'invalid cell areas')
    IF(REFERENCE_AREA==0.0_DP) THEN
      AREA_SUM=[SUM(REAL(ART(1:N),DP)),REAL(N,DP)];TOTAL=AREA_SUM
# if defined (MULTIPROCESSOR)
      IF(PAR) CALL MPI_ALLREDUCE(AREA_SUM,TOTAL,2,MPI_DOUBLE_PRECISION,MPI_SUM,MPI_FVCOM_GROUP,IERR)
# endif
      IF(TOTAL(2)<=0.0_DP) CALL FATAL_ERROR('BIHARMONIC MOMENTUM: empty global mesh')
      REFERENCE_AREA=REAL(MOMENTUM_BIHARMONIC_REFERENCE_AREA,DP)
      IF(REFERENCE_AREA==0.0_DP) REFERENCE_AREA=TOTAL(1)/TOTAL(2)
      IF(SERIAL.OR.MYID==1) WRITE(IPT,*) 'BIHARMONIC MOMENTUM: rate/day, reference area/m2=', &
        MOMENTUM_BIHARMONIC_RATE,REFERENCE_AREA
    END IF
    W%QX=0.0_SP;W%QY=0.0_SP;W%MASS=1.0_SP;W%COEF=0.0_SP
    DO I=1,N
      IF(ISBCE(I)==2) CYCLE
# if defined (WET_DRY)
      IF(IS3D) THEN
        IF(ISWETC(I)*ISWETCT(I)/=1) CYCLE
      ELSE
        IF(ISWETC(I)*ISWETCE(I)/=1) CYCLE
      END IF
# endif
      IF(IEEE_IS_FINITE(EPOR(I))) THEN
        IF(EPOR(I)/=1.0_SP) STATUS=1
      ELSE
        STATUS=1
      END IF
      W%QX(I,NL+1)=1.0_SP
      KAPPA=REAL(MOMENTUM_BIHARMONIC_RATE,DP)/86400.0_DP*SQRT(REFERENCE_AREA/REAL(ART(I),DP))
      DO K=1,NL
        IF(IS3D) THEN
          VOLUME=REAL(ART(I),DP)*REAL(DT1(I),DP)*REAL(DZ1(I,K),DP)
          W%QX(I,K)=U(I,K);W%QY(I,K)=V(I,K)
        ELSE
          VOLUME=REAL(ART(I),DP)*REAL(D1(I),DP)
          W%QX(I,K)=UA(I);W%QY(I,K)=VA(I)
        END IF
        IF(IEEE_IS_FINITE(VOLUME)) THEN
          IF(VOLUME<=0.0_DP.OR.VOLUME>=REAL(HUGE(1.0_SP),DP)) STATUS=1
          IF(IEEE_IS_FINITE(VOLUME*KAPPA)) THEN
            IF(VOLUME*KAPPA>=REAL(HUGE(1.0_SP),DP)) STATUS=1
          ELSE
            STATUS=1
          END IF
        ELSE
          STATUS=1
        END IF
        IF(STATUS==0) THEN
          W%MASS(I,K)=REAL(VOLUME,SP);W%COEF(I,K)=REAL(VOLUME*KAPPA,SP)
        END IF
      END DO
    END DO
    CALL CHECK_STATUS(STATUS,'invalid cell volume or unsupported nonunit interior porosity')
# if defined (MULTIPROCESSOR)
    IF(PAR) CALL AEXCHANGE(EC,MYID,NPROCS,W%QX,W%QY)
# endif
    W%ACTIVE=W%QX(:,NL+1)==1.0_SP;W%ACTIVE(0)=.FALSE.
  END SUBROUTINE

  SUBROUTINE EVALUATE(W,NL,DELT)
    TYPE(WORKSPACE),INTENT(INOUT)::W
    INTEGER,INTENT(IN)::NL
    REAL(SP),INTENT(IN)::DELT
    INTEGER::STATUS
    REAL(DP)::RATE,RATE_Y,GLOBAL_RATE
    CHARACTER(160)::DETAIL
# if defined (MULTIPROCESSOR)
    INTEGER::IERR
# endif
    CALL GRAPH_FILTER_FIRST(N,NT,NL,NBE,W%ACTIVE,W%QX,W%COEF,W%WX,W%ROW,STATUS)
    CALL CHECK_STATUS(STATUS,'invalid first-pass x field or topology')
    CALL GRAPH_FILTER_FIRST(N,NT,NL,NBE,W%ACTIVE,W%QY,W%COEF,W%WY,W%ROW,STATUS)
    CALL CHECK_STATUS(STATUS,'invalid first-pass y field or topology')
# if defined (MULTIPROCESSOR)
    IF(PAR) CALL AEXCHANGE(EC,MYID,NPROCS,W%WX,W%WY,W%ROW)
# endif
    CALL GRAPH_FILTER_SECOND(N,NT,NL,NBE,W%ACTIVE,W%WX,W%ROW,W%MASS,W%QX,RATE,STATUS)
    CALL CHECK_STATUS(STATUS,'invalid second-pass x field or volume')
    CALL GRAPH_FILTER_SECOND(N,NT,NL,NBE,W%ACTIVE,W%WY,W%ROW,W%MASS,W%QY,RATE_Y,STATUS)
    CALL CHECK_STATUS(STATUS,'invalid second-pass y field or volume')
    RATE=MAX(RATE,RATE_Y);GLOBAL_RATE=RATE
# if defined (MULTIPROCESSOR)
    IF(PAR) CALL MPI_ALLREDUCE(RATE,GLOBAL_RATE,1,MPI_DOUBLE_PRECISION,MPI_MAX,MPI_FVCOM_GROUP,IERR)
# endif
    STATUS=0
    IF(IEEE_IS_FINITE(DELT)) THEN
      IF(DELT<0.0_SP.OR.REAL(DELT,DP)*GLOBAL_RATE>0.8_DP) STATUS=1
    ELSE
      STATUS=1
    END IF
    WRITE(DETAIL,'(a,es12.4,a,es12.4)') 'explicit step*bound=',REAL(DELT,DP)*GLOBAL_RATE, &
      '; require <=0.8; maximum step/s=',0.8_DP/MAX(GLOBAL_RATE,TINY(1.0_DP))
    CALL CHECK_STATUS(STATUS,TRIM(DETAIL))
  END SUBROUTINE

  SUBROUTINE ADD_BIHARMONIC_3D(XFLUX,YFLUX)
    REAL(SP),INTENT(INOUT)::XFLUX(0:NT,KB),YFLUX(0:NT,KB)
    CALL CHECK_BIHARMONIC_CONFIG
    IF(MOMENTUM_BIHARMONIC_RATE==0.0_SP) RETURN
    CALL PREPARE(WORK3,KBM1,.TRUE.)
    CALL EVALUATE(WORK3,KBM1,DTI)
    XFLUX(1:N,1:KBM1)=XFLUX(1:N,1:KBM1)+WORK3%QX(1:N,1:KBM1)
    YFLUX(1:N,1:KBM1)=YFLUX(1:N,1:KBM1)+WORK3%QY(1:N,1:KBM1)
  END SUBROUTINE

  SUBROUTINE ADD_BIHARMONIC_2D(XFLUX,YFLUX)
    REAL(SP),INTENT(INOUT)::XFLUX(0:NT),YFLUX(0:NT)
    CALL CHECK_BIHARMONIC_CONFIG
    IF(MOMENTUM_BIHARMONIC_RATE==0.0_SP) RETURN
    CALL PREPARE(WORK2,1,.FALSE.)
    CALL EVALUATE(WORK2,1,DTE)
    XFLUX(1:N)=XFLUX(1:N)+WORK2%QX(1:N,1)
    YFLUX(1:N)=YFLUX(1:N)+WORK2%QY(1:N,1)
  END SUBROUTINE
END MODULE MOD_BIHARMONIC_MOMENTUM
